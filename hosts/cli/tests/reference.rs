//! The reference pages in `book/reference/` are generated, never written by
//! hand, so they cannot drift from the code:
//!
//! - `functions.md` from the one table of built-ins that signature help and
//!   completion read (`services::BUILTINS`), the prelude's functions
//!   as they read them (`Workspace::prelude_functions`), and the attributes
//!   the bundled modules declare, which they read beside it
//! - `libraries.md` from what `import(id)` gives a note for each bundled
//!   library, with each export's parameters and `//` comment from its source
//! - `collections.md` from `core/values/data/collections.md`: each collection
//!   a query binds, an example command run on `examples` with its output, and
//!   a description of every field its records have there. A field with no
//!   description, or a description of a field no record has, fails the test
//! - `writing-modules.md` from `core/modules/data/kinds.md`, laid out over the
//!   hooks, records and `step` loops of `core/modules/data/hooks.md` and what
//!   native code calls in the stdlib (`lang::stdlib::CONTRACT`). Every example
//!   module compiles, and every record is shown under a kind
//!
//! A page that differs from what the code generates fails the test; rewrite
//! the pages with `UPDATE_SNAPSHOTS=1`.
mod support;

use lang::eval::modules::Collection;
use lang::syntax::Tier;
use serde_json::Value;
use services::{BUILTINS, Signature};
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write as _,
    path::{Path, PathBuf},
    process::Command,
};

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

#[test]
fn reference_pages_are_current() {
    let pages = [
        ("functions.md", functions()),
        ("libraries.md", libraries()),
        ("collections.md", collections()),
        ("writing-modules.md", writing_modules()),
    ];
    let update = support::update_snapshots();
    let directory = repo().join("book/reference");
    let mut stale = Vec::new();
    for (name, generated) in pages {
        let path = directory.join(name);
        if update {
            std::fs::create_dir_all(&directory).unwrap();
            std::fs::write(&path, generated).unwrap();
        } else if std::fs::read_to_string(&path).ok().as_deref() != Some(&generated) {
            stale.push(name);
        }
    }
    assert!(
        stale.is_empty(),
        "book/reference is stale: {}\nRerun with UPDATE_SNAPSHOTS=1 and commit the pages.",
        stale.join(", ")
    );
}

/// `xmd query --help` names the same bindings a query can use.
#[test]
fn query_help_lists_every_binding() {
    let output = xmd(&repo(), &["query", "--help"]);
    let listed: BTreeSet<&str> = output
        .lines()
        .find_map(|line| line.strip_prefix("Bindings: "))
        .expect("no Bindings line in `xmd query --help`")
        .split(", ")
        .collect();
    assert_eq!(listed, bindings().iter().map(String::as_str).collect());
}

